# -*- coding: utf-8 -*-
"""断链引号规则回归测试。

用法： python tests/test_dangling.py

断言两类：
  A. 干净文本零改动（合法对话/多段对话/合法嵌套强调/外双内单）
  B. 病态文本 → 期望结果（全部条目来自真实小说的人工校对结果）
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "scripts"))

import punct_rules as rules  # noqa: E402

CLEAN = [
    "“你来了。”他说。",
    "“谈钱就俗了。”他伸手把钱推了回去，“不是点了酒水吗？”",
    "他笑了笑。“你好。”",
    "“她说‘我不去’，然后就走了。”",
    "他按下了“添加到通讯录”的按钮。",
    "“外“内”外”",                       # 合法嵌套强调（平衡行）
    "“我这个人呢，最讲情谊。”她特意加重了“敬重”二字。",
    "“尾数是17，老师。”陈惊鸿恭敬地回答，“好像就在这儿。”",
    "“别闹，”陈惊鸿抓住她的手，“我在做饭。”",
    "他说：“明天见。”",
]

FIX = [
    # 倒置强调对
    ("她用了些“捏“学生的小手段。", "她用了些“捏”学生的小手段。"),
    ("他按下了“添加到通讯录“的按钮。“苏晴。”",
     "他按下了“添加到通讯录”的按钮。“苏晴。”"),
    ("她看向仍在“愧恼“和“自卑”的陈惊鸿：“今天是老师不对。”",
     "她看向仍在“愧恼”和“自卑”的陈惊鸿：“今天是老师不对。”"),
    # 对话＋旁白＋新对话（左侧句读后的倒置闭引号优先）
    ("“我这个人呢，最重苏老师了。“她特意加重了“敬重”二字，格外讽刺。",
     "“我这个人呢，最重苏老师了。”她特意加重了“敬重”二字，格外讽刺。"),
    ("红色的钞票散开。“这些都给你。“她的声音发紧，“我们两清。”",
     "红色的钞票散开。“这些都给你。”她的声音发紧，“我们两清。”"),
    # 行首漏开引号（补开 + 翻正）
    ("我只是还给你而已，“他俯身靠近，温热的呼吸拂过她的耳廊，“你怎么就受不了了？",
     "“我只是还给你而已，”他俯身靠近，温热的呼吸拂过她的耳廊，“你怎么就受不了了？”"),
    ("九十分可以吗？老师？“陈惊鸿的声音有些发干，“会不会太高了？”",
     "“九十分可以吗？老师？”陈惊鸿的声音有些发干，“会不会太高了？”"),
    # 行首叠引
    ("““老师，您接触的优秀学生那么多。”苏晴的心紧了一下。",
     "“老师，您接触的优秀学生那么多。”苏晴的心紧了一下。"),
    # 行尾孤立开引号
    ("没想到，白天是讲师的她，私下是却是反差的！“", "没想到，白天是讲师的她，私下是却是反差的！"),
]


def main():
    bad = 0
    for s in CLEAN:
        got, n = rules.fix_dangling_quotes(s)
        if got != s:
            bad += 1
            print(f"[干净文本被改] {s}\n            → {got}")

    for src, want in FIX:
        got, n = rules.fix_dangling_quotes(src)
        if got != want:
            bad += 1
            print(f"[期望不符] {src}\n        期望 {want}\n        实际 {got}")

    # 幂等：修复结果再跑一次应零改动
    for src, want in FIX:
        got, _ = rules.fix_dangling_quotes(src)
        again, n2 = rules.fix_dangling_quotes(got)
        if n2 or again != got:
            bad += 1
            print(f"[不幂等] {got} → {again}")

    total = len(CLEAN) + len(FIX) * 2
    print(f"\n{'全部通过' if not bad else '存在失败'}：{total - bad}/{total}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
